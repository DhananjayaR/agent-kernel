// `pnpm compile-schemas`: turns every `*.schema.json` under apps/renderer/src into a precompiled validator,
// `*.validate.js` (an ES module) with its types in `*.validate.d.ts`, both next to the schema (P0 D12).
//
// Why precompiled: Ajv's runtime `compile` builds the validator with `new Function`, which the renderer CSP
// (`script-src 'self'`) refuses, so the code is generated here with Ajv standalone and committed. The output is
// strict: `coerceTypes` off (a string "30" for an integer is rejected), Ajv strict mode, every error reported.
// Annotations (description, title, $comment) are dropped before compiling: a validator does not need them, and
// schema prose then never reaches the bundle (nor the palette check).
//
//   node tools/compile-schemas.mjs           write the validators
//   node tools/compile-schemas.mjs --check   fail if any committed validator differs from a fresh compile
//                                            (run by `pnpm lint`, `pnpm build` and `pnpm build:e2e`)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const Ajv2020 = require("ajv/dist/2020").default;
const standaloneCode = require("ajv/dist/standalone").default;

export const STUDIO = fileURLToPath(new URL("../", import.meta.url)).replace(
	/\/$/,
	"",
);
export const DEFAULT_ROOTS = ["apps/renderer/src"];
const SKIP_DIRS = new Set(["node_modules", "dist", "out", "storybook-static"]);
const SCHEMA_FILE = /\.schema\.json$/;
const ANNOTATIONS = new Set(["description", "title", "$comment"]);

/** The schema with annotation keywords removed (they never change what validates). */
function withoutAnnotations(node) {
	if (Array.isArray(node)) return node.map(withoutAnnotations);
	if (node === null || typeof node !== "object") return node;
	const out = {};
	for (const [key, value] of Object.entries(node)) {
		if (ANNOTATIONS.has(key)) continue;
		// Under `properties` and `$defs` the keys are names, not keywords: a property may be called "title".
		out[key] =
			key === "properties" || key === "$defs"
				? Object.fromEntries(
						Object.entries(value).map(([k, v]) => [k, withoutAnnotations(v)]),
					)
				: withoutAnnotations(value);
	}
	return out;
}

const banner = (sourceName) =>
	`// Generated by tools/compile-schemas.mjs from ${sourceName} (Ajv standalone, strict, coerceTypes off).\n` +
	"// Do not edit: change the schema and run `pnpm compile-schemas`.\n";

/** The ES module source of a strict, precompiled validator for `schema`. */
export function compileSchema(schema, sourceName) {
	const ajv = new Ajv2020({
		strict: true,
		allErrors: true,
		coerceTypes: false,
		useDefaults: false,
		code: { source: true, esm: true },
	});
	const validate = ajv.compile(withoutAnnotations(schema));
	return `${banner(sourceName)}${standaloneCode(ajv, validate)}\n`;
}

/** The `.d.ts` beside a validator: the default export, typed by its shape (no `ajv` import in the renderer). */
export function declarationSource(sourceName) {
	return `${banner(sourceName)}declare const validate: {
	(data: unknown): boolean;
	errors?: Array<{
		instancePath: string;
		schemaPath: string;
		keyword: string;
		params: Record<string, unknown>;
		message?: string;
	}> | null;
};
export default validate;
`;
}

function* schemaFiles(dir) {
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		if (entry.isDirectory()) {
			if (!SKIP_DIRS.has(entry.name)) yield* schemaFiles(join(dir, entry.name));
		} else if (entry.isFile() && SCHEMA_FILE.test(entry.name)) {
			yield join(dir, entry.name);
		}
	}
}

/** Every `*.schema.json` under `roots` (relative to ak-studio/), sorted. */
export function findSchemas(roots = DEFAULT_ROOTS) {
	return roots
		.flatMap((root) => [...schemaFiles(resolve(STUDIO, root))])
		.sort();
}

const readOrNull = (file) => {
	try {
		return readFileSync(file, "utf8");
	} catch {
		return null;
	}
};

/**
 * Compiles every schema. With `check`, writes nothing and returns the outputs that are missing or differ
 * (paths relative to ak-studio/) in `stale`; otherwise writes them and returns them in `written`.
 */
export function compileSchemas({ check = false, roots = DEFAULT_ROOTS } = {}) {
	const written = [];
	const stale = [];
	for (const schemaPath of findSchemas(roots)) {
		const name = basename(schemaPath);
		const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
		const base = schemaPath.replace(SCHEMA_FILE, "");
		const outputs = [
			[`${base}.validate.js`, compileSchema(schema, name)],
			[`${base}.validate.d.ts`, declarationSource(name)],
		];
		for (const [file, source] of outputs) {
			const rel = relative(STUDIO, file);
			if (check) {
				if (readOrNull(file) !== source) stale.push(rel);
			} else {
				writeFileSync(file, source);
				written.push(rel);
			}
		}
	}
	return { written, stale };
}

function main(argv) {
	const check = argv.includes("--check");
	const { written, stale } = compileSchemas({ check });
	if (check) {
		if (stale.length > 0) {
			console.error(
				`compile-schemas FAILED: out of date, run \`pnpm compile-schemas\`:\n  ${stale.join("\n  ")}`,
			);
			return 1;
		}
		console.log(
			`compile-schemas OK: ${findSchemas().length} validators up to date`,
		);
		return 0;
	}
	console.log(`compile-schemas wrote:\n  ${written.join("\n  ")}`);
	return 0;
}

if (
	process.argv[1] &&
	resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
	process.exitCode = main(process.argv.slice(2));
}

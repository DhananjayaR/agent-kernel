// `pnpm third-party-notices`: rewrites the code section of apps/desktop/resources/THIRD-PARTY-NOTICES.txt from what
// the production build actually bundles. Run it after a dependency change and commit the file.
//
// It builds main, preload and the renderer with source maps into a temporary folder (`electron-vite build
// --sourcemap`), takes every package under node_modules/ that a source map names, and writes each one's name,
// version, licence and licence file (verbatim) between the markers below. The renderer's CSS has no source map,
// so the packages its stylesheet compiles in are listed by hand in CSS_PACKAGES. The fonts section above the
// markers is kept as it is. Electron's and Chromium's own licences ship beside the app (LICENSE.electron.txt,
// LICENSES.chromium.html, written by electron-builder).
import { execFileSync } from "node:child_process";
import {
	mkdtempSync,
	readdirSync,
	readFileSync,
	realpathSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const STUDIO = fileURLToPath(new URL("../", import.meta.url));
const DESKTOP = join(STUDIO, "apps/desktop");
const NOTICES = join(DESKTOP, "resources/THIRD-PARTY-NOTICES.txt");
const BEGIN =
	"=== Bundled code (generated by `pnpm third-party-notices`; do not edit by hand) ===";
/** Compiled into the renderer's stylesheet (packages/ui/src/theme.css): Tailwind's preflight and tw-animate-css. */
const CSS_PACKAGES = ["tailwindcss", "tw-animate-css"];
const RULE = "-".repeat(108);

function mapFiles(dir) {
	return readdirSync(dir, { recursive: true })
		.filter((f) => f.endsWith(".map"))
		.map((f) => join(dir, f));
}

/** The package root of a file under node_modules/, or undefined. */
function packageRoot(file) {
	const marker = "/node_modules/";
	const at = file.lastIndexOf(marker);
	if (at < 0) return undefined;
	const parts = file.slice(at + marker.length).split("/");
	const name = parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0];
	return file.slice(0, at + marker.length) + name;
}

function describe(root) {
	const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
	const files = readdirSync(root).filter((f) =>
		/^(licen[cs]e|notice)/i.test(f),
	);
	if (files.length === 0)
		throw new Error(`${pkg.name}: no licence file in ${root}`);
	return {
		name: pkg.name,
		version: pkg.version,
		license: pkg.license,
		texts: files.sort().map((f) => readFileSync(join(root, f), "utf8").trim()),
	};
}

const out = mkdtempSync(join(tmpdir(), "ak-studio-notices-"));
try {
	execFileSync(
		"pnpm",
		["exec", "electron-vite", "build", "--sourcemap", "--outDir", out],
		{
			cwd: DESKTOP,
			stdio: "ignore",
		},
	);
	const roots = new Set();
	for (const map of mapFiles(out)) {
		const { sources } = JSON.parse(readFileSync(map, "utf8"));
		for (const source of sources) {
			const root = packageRoot(resolve(dirname(map), source));
			if (root) roots.add(root);
		}
	}
	// packages/ui depends on them; pnpm links each into its node_modules.
	for (const name of CSS_PACKAGES) {
		roots.add(realpathSync(join(STUDIO, "packages/ui/node_modules", name)));
	}
	const packages = [...roots]
		.map(describe)
		.sort((a, b) => a.name.localeCompare(b.name));

	const section = [
		BEGIN,
		"",
		"Code bundled into the app (main process and renderer), with each package's licence as it publishes it.",
		"",
		...packages.map((p) => `- ${p.name} ${p.version} (${p.license})`),
		"",
		...packages.flatMap((p) => [
			RULE,
			"",
			`${p.name} ${p.version} (${p.license})`,
			"",
			...p.texts,
			"",
		]),
	].join("\n");

	const current = readFileSync(NOTICES, "utf8");
	const at = current.indexOf(BEGIN);
	let fonts = (at < 0 ? current : current.slice(0, at)).trimEnd();
	if (fonts.endsWith(RULE)) fonts = fonts.slice(0, -RULE.length).trimEnd();
	writeFileSync(NOTICES, `${fonts}\n\n${RULE}\n\n${section}`);
	console.log(
		`third-party-notices: ${packages.length} packages: ${packages.map((p) => p.name).join(", ")}`,
	);
} finally {
	rmSync(out, { recursive: true, force: true });
}
